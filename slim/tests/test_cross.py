"""Cross builds pick each target's dependencies without running its interpreter (slim/cross.py).

The requirement lines are verbatim from `uv export` of this repository's uv.lock.
"""

import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import cross

NEMO = ("nemo-relay==0.10.3 ; (python_full_version >= '3.14' and platform_machine == 'aarch64' and 'android' not in platform_release and sys_platform == 'linux') "
        "or (python_full_version >= '3.14' and platform_machine == 'x86_64' and 'android' not in platform_release and sys_platform == 'linux') "
        "or (python_full_version >= '3.14' and platform_machine == 'arm64' and sys_platform == 'darwin') "
        "or (python_full_version >= '3.14' and platform_machine == 'AMD64' and sys_platform == 'win32') "
        "or (python_full_version >= '3.14' and platform_machine == 'ARM64' and sys_platform == 'win32')")
RUAMEL = ("ruamel-yaml-clib==0.2.15 ; (python_full_version >= '3.14' and platform_machine in 'x86_64 aarch64 i686' and platform_python_implementation == 'CPython' and sys_platform == 'linux') "
          "or (python_full_version >= '3.14' and platform_machine in 'AMD64 x86' and platform_python_implementation == 'CPython' and sys_platform == 'win32') "
          "or (python_full_version >= '3.14' and platform_python_implementation == 'CPython' and sys_platform == 'darwin')")
PYWIN32 = "pywin32==311 ; sys_platform == 'win32'"
UVLOOP = "uvloop==0.22.1 ; platform_python_implementation != 'PyPy' and sys_platform != 'cygwin' and sys_platform != 'win32'"
OLD = "exceptiongroup==1.3.0 ; python_full_version < '3.11'"
EXPORT = "\n".join(["# generated by uv", "anyio==4.11.0", NEMO, "    # via hermes-agent", RUAMEL, PYWIN32, UVLOOP, OLD, ""])


def names(target):
    return {line.split("==")[0] for line in cross.select_requirements(EXPORT, cross.marker_env(target, "3.14.9"))}


class SelectRequirements(unittest.TestCase):
    def test_windows_keeps_requirements_gated_on_amd64(self):
        # uv's x86_64-pc-windows-msvc platform calls the machine x86_64 and dropped these.
        self.assertEqual(names("win32-x64"), {"anyio", "nemo-relay", "ruamel-yaml-clib", "pywin32"})

    def test_each_target_gets_its_own_platform_packages(self):
        self.assertEqual(names("linux-x64"), {"anyio", "nemo-relay", "ruamel-yaml-clib", "uvloop"})
        self.assertEqual(names("linux-arm64"), {"anyio", "nemo-relay", "ruamel-yaml-clib", "uvloop"})
        self.assertEqual(names("darwin-arm64"), {"anyio", "nemo-relay", "ruamel-yaml-clib", "uvloop"})
        self.assertEqual(names("darwin-x64"), {"anyio", "ruamel-yaml-clib", "uvloop"})

    def test_output_is_marker_free_pins(self):
        for line in cross.select_requirements(EXPORT, cross.marker_env("win32-x64", "3.14.9")):
            self.assertRegex(line, r"^[A-Za-z0-9_.\-]+==[^ ;]+$")

    def test_version_comparisons_pad_and_wildcard(self):
        env = cross.marker_env("linux-x64", "3.14.9")
        for marker, want in (("python_full_version >= '3.14'", True), ("python_full_version < '3.14.10'", True),
                             ("python_version == '3.14.*'", True), ("python_version != '3.14.*'", False),
                             ("python_full_version ~= '3.14.0'", True), ("python_full_version ~= '3.13.0'", False),
                             ("'3.13' < python_version", True), ("(os_name == 'nt' or os_name == 'posix') and extra == ''", True)):
            self.assertEqual(cross.evaluate_marker(marker, env), want, marker)

    def test_unknown_variable_fails_loudly(self):
        with self.assertRaises(ValueError):
            cross.evaluate_marker("platform_flavour == 'x'", cross.marker_env("linux-x64", "3.14.9"))

    @unittest.skipUnless(shutil.which("uv"), "needs uv")
    def test_uv_installs_the_selection_for_windows(self):
        # What the cross build hands uv: with the markers resolved here, uv cannot drop them.
        with tempfile.TemporaryDirectory() as tmp:
            reqs = Path(tmp) / "reqs.txt"
            reqs.write_text("\n".join(cross.select_requirements("\n".join([NEMO, RUAMEL]), cross.marker_env("win32-x64", "3.14.9"))))
            out = subprocess.run(["uv", "pip", "install", "--dry-run", "--target", str(Path(tmp) / "t"), "--python-platform",
                                  cross.UV_PLATFORM["win32-x64"], "--python-version", "3.14.9", "--no-deps", "--no-build",
                                  "-r", str(reqs)], capture_output=True, text=True, timeout=300, check=False,
                                 env={**__import__("os").environ, "UV_NO_CONFIG": "1"})
            self.assertEqual(out.returncode, 0, out.stderr)
            self.assertIn("nemo-relay==0.10.3", out.stderr)
            self.assertIn("ruamel-yaml-clib==0.2.15", out.stderr)


class Paths(unittest.TestCase):
    def test_neutral_round_trips_for_every_target(self):
        for target in cross.UV_PLATFORM:
            for key in ("SP/anyio/__init__.py", "STD/asyncio/events.py", "app/cli.py"):
                self.assertEqual(cross.neutral(cross.localize(key, target, "3.14.9"), target, "3.14.9"), key)
        self.assertEqual(cross.localize("SP/x.py", "win32-x64", "3.14.9"), "python/Lib/site-packages/x.py")
        self.assertEqual(cross.localize("STD/x.py", "darwin-arm64", "3.14.9"), "python/lib/python3.14/x.py")

    def test_warm_extras_exist_for_every_cross_target(self):
        # The Windows first launch imports ~300 modules a Linux one never does.
        self.assertGreater(len(cross.warm_extras("win32-x64")), 100)
        for target in ("darwin-x64", "darwin-arm64"):
            self.assertTrue(cross.warm_extras(target), target)


if __name__ == "__main__":
    unittest.main()
